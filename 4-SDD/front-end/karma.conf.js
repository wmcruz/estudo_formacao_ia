const fs = require('fs');

if (!process.env.CHROME_BIN) {
  const possiblePaths = [
    '/usr/bin/google-chrome',
    '/usr/bin/google-chrome-stable',
    '/usr/bin/chromium',
    '/usr/bin/chromium-browser'
  ];
  for (const path of possiblePaths) {
    if (fs.existsSync(path)) {
      process.env.CHROME_BIN = path;
      break;
    }
  }
}

